# ЭКСПОРТ СКРИПТА ОЧИСТКИ
# ============================================================

function Export-CleanupScript {
    <#
    .SYNOPSIS
        Генерирует PowerShell-скрипт для замены дубликатов на хардлинки.
    .DESCRIPTION
        Только создаёт файл. НЕ выполняет никаких действий.
    #>
    param(
        [array]$DuplicateGroups,
        [string]$OutputPath = ".\output\cleanup.ps1",
        [ValidateSet("Hardlink", "Delete")]
        [string]$Action = "Hardlink"
    )
    
    Write-Host "`n[6/6] Exporting cleanup script..." -ForegroundColor Yellow
    
    # Собираем действия
    $actions = @()
    foreach ($group in $DuplicateGroups) {
        if ($group.RegularFiles.Count -lt 2) { continue }
        
        $source = $group.RegularFiles[0].FullPath
        for ($i = 1; $i -lt $group.RegularFiles.Count; $i++) {
            $actions += [PSCustomObject]@{
                Source = $source
                Target = $group.RegularFiles[$i].FullPath
                Size   = $group.Size
            }
        }
    }
    
    Write-Host "  Actions to export: $($actions.Count)" -ForegroundColor Gray
    
    if ($actions.Count -eq 0) {
        Write-Host "  Nothing to export." -ForegroundColor Green
        return
    }
    
    # Генерируем скрипт
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("# ============================================================")
    [void]$sb.AppendLine("# Cleanup script (generated by find-dupes.ps1)")
    [void]$sb.AppendLine("# Date: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
    [void]$sb.AppendLine("# Action: $Action")
    [void]$sb.AppendLine("# Total: $($actions.Count) operations")
    [void]$sb.AppendLine("# ============================================================")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("param([switch]`$WhatIf = `$false)")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("`$actions = @(")
    
    $actionLines = @()
    foreach ($a in $actions) {
        $src = $a.Source -replace "'", "''"
        $tgt = $a.Target -replace "'", "''"
        $actionLines += "    @{ Source = '$src'; Target = '$tgt' }"
    }
    [void]$sb.AppendLine(($actionLines -join ",`n"))
    
    [void]$sb.AppendLine(")")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("`$ok = 0")
    [void]$sb.AppendLine("`$err = 0")
    [void]$sb.AppendLine("`$count = 0")
    [void]$sb.AppendLine("foreach (`$a in `$actions) {")
    [void]$sb.AppendLine("    `$count++")
    [void]$sb.AppendLine("    if (`$WhatIf) {")
    [void]$sb.AppendLine("        Write-Host ""[`$count/`$(`$actions.Count)] WOULD: `$(`$a.Target) -> `$(`$a.Source)"" -ForegroundColor Cyan")
    [void]$sb.AppendLine("        continue")
    [void]$sb.AppendLine("    }")
    
    if ($Action -eq "Hardlink") {
        [void]$sb.AppendLine("    `$backup = `$null")
        [void]$sb.AppendLine("    try {")
        [void]$sb.AppendLine("        if (-not (Test-Path -LiteralPath `$a.Source)) { throw 'Source not found' }")
        [void]$sb.AppendLine("        if (-not (Test-Path -LiteralPath `$a.Target)) { throw 'Target not found' }")
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("        # 1. Rename target (backup)")
        [void]$sb.AppendLine("        `$backup = `$a.Target + '.todel'")
        [void]$sb.AppendLine("        if (Test-Path -LiteralPath `$backup) { Remove-Item -LiteralPath `$backup -Force }")
        [void]$sb.AppendLine("        Rename-Item -LiteralPath `$a.Target -NewName (Split-Path `$backup -Leaf) -Force")
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("        # 2. Create hardlink via mklink (bypasses wildcard issues with [ ])")
        [void]$sb.AppendLine("        `$mklinkCmd = 'mklink /H ""' + `$a.Target + '"" ""' + `$a.Source + '""'")
        [void]$sb.AppendLine("        `$result = cmd /c `$mklinkCmd 2>&1")
        [void]$sb.AppendLine("        if (`$LASTEXITCODE -ne 0) { throw ""mklink failed: `$result"" }")
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("        # 3. Remove backup")
        [void]$sb.AppendLine("        Remove-Item -LiteralPath `$backup -Force")
        [void]$sb.AppendLine("        `$backup = `$null")
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("        Write-Host ""[`$count/`$(`$actions.Count)] OK: `$(`$a.Target)"" -ForegroundColor Green")
        [void]$sb.AppendLine("        `$ok++")
        [void]$sb.AppendLine("    } catch {")
        [void]$sb.AppendLine("        Write-Host ""[`$count/`$(`$actions.Count)] ERROR: `$(`$a.Target): `$(`$_.Exception.Message)"" -ForegroundColor Red")
        [void]$sb.AppendLine("        if (`$backup -and (Test-Path -LiteralPath `$backup)) {")
        [void]$sb.AppendLine("            if (-not (Test-Path -LiteralPath `$a.Target)) {")
        [void]$sb.AppendLine("                Rename-Item -LiteralPath `$backup -NewName (Split-Path `$a.Target -Leaf) -Force -ErrorAction SilentlyContinue")
        [void]$sb.AppendLine("            }")
        [void]$sb.AppendLine("        }")
        [void]$sb.AppendLine("        `$err++")
        [void]$sb.AppendLine("    }")
    } elseif ($Action -eq "Delete") {
        [void]$sb.AppendLine("    try {")
        [void]$sb.AppendLine("        if (-not (Test-Path -LiteralPath `$a.Target)) { throw 'Target not found' }")
        [void]$sb.AppendLine("        Remove-Item -LiteralPath `$a.Target -Force")
        [void]$sb.AppendLine("        Write-Host ""[`$count/`$(`$actions.Count)] DELETED: `$(`$a.Target)"" -ForegroundColor Yellow")
        [void]$sb.AppendLine("        `$ok++")
        [void]$sb.AppendLine("    } catch {")
        [void]$sb.AppendLine("        Write-Host ""[`$count/`$(`$actions.Count)] ERROR: `$(`$a.Target): `$(`$_.Exception.Message)"" -ForegroundColor Red")
        [void]$sb.AppendLine("        `$err++")
        [void]$sb.AppendLine("    }")
    }
    
    [void]$sb.AppendLine("}")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("Write-Host ""``nDone. OK: `$ok, Errors: `$err, Total: `$(`$actions.Count)"" -ForegroundColor Cyan")
    
    # Сохраняем
    $dir = Split-Path -Parent $OutputPath
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    $sb.ToString() | Out-File -FilePath $OutputPath -Encoding UTF8
    Write-Host "  Script saved: $OutputPath" -ForegroundColor Green
    Write-Host "  Run it manually: .\output\cleanup.ps1" -ForegroundColor DarkGray
    Write-Host "  Dry-run: .\output\cleanup.ps1 -WhatIf" -ForegroundColor DarkGray
}
